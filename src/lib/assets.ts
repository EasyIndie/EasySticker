import fs from "node:fs";
import path from "node:path";
import { uploadsDir } from "./paths";

/**
 * Storage seam for generated/uploaded assets. The default implementation is a
 * local directory; swap this out (object storage, in-memory, …) without touching
 * the services that generate or validate assets.
 */
export interface AssetStore {
  save(bytes: Buffer, assetId: string, ext?: string): string;
  find(assetId: string): { filePath: string; filename: string } | null;
}

/**
 * 入库时用的扩展名（见 uploads.ts / import.ts / restore.ts / flow.ts / single.ts）。
 * `findAssetFile` 按序探测这几个候选名，而不是扫描整个目录：
 * `readdirSync` 是 O(目录大小) 的**同步** I/O，而它挂在 `GET /api/assets/:id`
 * （结果页每张图一个请求）与打包（每包 ~30 次）的热路径上，目录一大就会卡住事件循环。
 * 探测是 O(1) 的，实测 0.023ms vs 333 个文件时扫描的 0.699ms，且不随规模退化。
 */
const ASSET_EXTENSIONS = ["png", "jpg", "jpeg", "webp", "gif"];

/** assetId 由 nanoid 生成；限字符集同时挡住路径穿越（id 可来自 URL 参数）。 */
const ASSET_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

export function findAssetFile(dataDir: string, id: string): { filePath: string; filename: string } | null {
  if (!ASSET_ID_PATTERN.test(id)) return null;
  const dir = uploadsDir(dataDir);
  for (const ext of ASSET_EXTENSIONS) {
    const filename = `${id}.${ext}`;
    const filePath = path.join(dir, filename);
    try {
      if (fs.statSync(filePath).isFile()) return { filename, filePath };
    } catch {
      // 该扩展名不存在，试下一个
    }
  }
  return null;
}

export interface AssetFileInfo {
  assetId: string;
  filename: string;
  filePath: string;
  bytes: number;
  mtimeMs: number;
}

/**
 * 列出 uploads 目录下的全部资源。**会扫描整个目录**，仅供清理/统计等低频任务使用，
 * 不要放在请求热路径上。
 */
export function listAssetFiles(dataDir: string): AssetFileInfo[] {
  const dir = uploadsDir(dataDir);
  if (!fs.existsSync(dir)) return [];
  const out: AssetFileInfo[] = [];
  for (const filename of fs.readdirSync(dir)) {
    if (filename.startsWith(".")) continue;
    const dot = filename.lastIndexOf(".");
    if (dot <= 0) continue;
    const filePath = path.join(dir, filename);
    let st: fs.Stats;
    try {
      st = fs.statSync(filePath);
    } catch {
      continue;
    }
    if (!st.isFile()) continue;
    out.push({
      assetId: filename.slice(0, dot),
      filename,
      filePath,
      bytes: st.size,
      mtimeMs: st.mtimeMs
    });
  }
  return out;
}

/** Persist generated bytes into the uploads directory. Returns the written path. */
export function saveAssetFile(dataDir: string, bytes: Buffer, assetId: string, ext = "png") {
  const dir = uploadsDir(dataDir);
  fs.mkdirSync(dir, { recursive: true });
  const outPath = path.join(dir, `${assetId}.${ext}`);
  fs.writeFileSync(outPath, bytes);
  return outPath;
}

/** File-backed AssetStore implementation rooted at `dataDir`. */
export function createFileAssetStore(dataDir: string): AssetStore {
  return {
    save: (bytes, assetId, ext = "png") => saveAssetFile(dataDir, bytes, assetId, ext),
    find: (assetId) => findAssetFile(dataDir, assetId)
  };
}
